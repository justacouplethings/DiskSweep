    private void AddBrowserTargets(CleanCategory category, string browserName, string profilePath)
    {
        if (!Directory.Exists(profilePath)) return;

        string cache = Path.Combine(profilePath, "Cache");
        if (Directory.Exists(cache))
        {
            category.AddItem(new CleanItem
            {
                Name = $"{browserName} HTTP Cache",
                TargetPath = cache,
                Description = $"Cached web images and styles for {browserName}.",
                Safety = SafetyLevel.Safe
            });
        }

        string codeCache = Path.Combine(profilePath, "Code Cache");
        if (Directory.Exists(codeCache))
        {
            category.AddItem(new CleanItem
            {
                Name = $"{browserName} Code Cache",
                TargetPath = codeCache,
                Description = $"Compiled WebAssembly and JavaScript cache for {browserName}.",
                Safety = SafetyLevel.Safe
            });
        }

        string gpuCache = Path.Combine(profilePath, "GPUCache");
        if (Directory.Exists(gpuCache))
        {
            category.AddItem(new CleanItem
            {
                Name = $"{browserName} GPU Cache",
                TargetPath = gpuCache,
                Description = $"Hardware-accelerated shader cache for {browserName}.",
                Safety = SafetyLevel.Safe
            });
        }
    }

    public async Task ScanCategoryAsync(CleanCategory category, CancellationToken ct)
    {
        foreach (var item in category.Items)
        {
            if (ct.IsCancellationRequested) break;
            await ScanItemAsync(item, ct);
        }
        category.RefreshSummary();
    }

    public async Task ScanItemAsync(CleanItem item, CancellationToken ct)
    {
        item.IsScanning = true;
        item.Status = "Scanning...";

        try
        {
            if (item.IsRecycleBin)
            {
                var (bytes, count) = NativeMethods.GetRecycleBinStats(null);
                item.Size = bytes;
                item.ItemCount = (int)count;
                item.Status = count > 0 ? $"{count:N0} items" : "Empty";
                return;
            }

            if (!Directory.Exists(item.TargetPath))
            {
                item.Size = 0;
                item.ItemCount = 0;
                item.Status = "Not found";
                return;
            }

            // Perform fast directory enumeration in background thread
            var (totalBytes, fileCount) = await Task.Run(() => ComputeDirectorySize(item.TargetPath, ct), ct);
            item.Size = totalBytes;
            item.ItemCount = fileCount;
            item.Status = fileCount > 0 ? "Ready to clean" : "Empty";
        }
        catch (OperationCanceledException)
        {
            item.Status = "Cancelled";
        }
        catch (Exception ex)
        {
            item.Status = $"Error: {ex.Message}";
        }
        finally
        {
            item.IsScanning = false;
        }
    }

    private (long bytes, int files) ComputeDirectorySize(string rootPath, CancellationToken ct)
    {
        long totalBytes = 0;
        int fileCount = 0;

        try
        {
            var stack = new Stack<string>();
            stack.Push(rootPath);

            while (stack.Count > 0)
            {
                if (ct.IsCancellationRequested) break;

                string currentDir = stack.Pop();
                try
                {
                    var dirInfo = new DirectoryInfo(currentDir);
                    foreach (var file in dirInfo.EnumerateFiles())
                    {
                        if (ct.IsCancellationRequested) break;
                        try
                        {
                            totalBytes += file.Length;
                            fileCount++;
                        }
                        catch { }
                    }

                    foreach (var subDir in dirInfo.EnumerateDirectories())
                    {
                        if (ct.IsCancellationRequested) break;
                        try
                        {
                            // Avoid following recursive reparse points / symlinks
                            if ((subDir.Attributes & FileAttributes.ReparsePoint) == 0)
                            {
                                stack.Push(subDir.FullName);
                            }
                        }
                        catch { }
                    }
                }
                catch { }
            }
        }
        catch { }

        return (totalBytes, fileCount);
    }

    public async Task<(int deletedFiles, long freedBytes, int skippedFiles)> CleanItemAsync(
        CleanItem item, 
        IProgress<CleanProgress>? progress, 
        CancellationToken ct)
    {
        int deletedFiles = 0;
        long freedBytes = 0;
        int skippedFiles = 0;

        if (item.IsRecycleBin)
        {
            try
            {
                long prevSize = item.Size;
                int prevCount = item.ItemCount;
                int hr = NativeMethods.SHEmptyRecycleBin(IntPtr.Zero, null, 
                    NativeMethods.SHERB_NOCONFIRMATION | NativeMethods.SHERB_NOPROGRESSUI | NativeMethods.SHERB_NOSOUND);
                if (hr == 0)
                {
                    deletedFiles = prevCount;
                    freedBytes = prevSize;
                    item.Size = 0;
                    item.ItemCount = 0;
                    item.Status = "Cleaned";
                }
            }
            catch
            {
                skippedFiles++;
            }
            return (deletedFiles, freedBytes, skippedFiles);
        }

        if (!Directory.Exists(item.TargetPath))
        {
            item.Status = "Skipped (Path missing)";
            return (0, 0, 0);
        }

        await Task.Run(() =>
        {
            try
            {
                var dirInfo = new DirectoryInfo(item.TargetPath);

                // Delete files in root
                foreach (var file in dirInfo.EnumerateFiles())
                {
                    if (ct.IsCancellationRequested) break;
                    try
                    {
                        long len = file.Length;
                        // Strip read-only if present
                        if ((file.Attributes & FileAttributes.ReadOnly) != 0)
                        {
                            file.Attributes &= ~FileAttributes.ReadOnly;
                        }
                        file.Delete();
                        deletedFiles++;
                        freedBytes += len;
                        progress?.Report(new CleanProgress(file.Name, deletedFiles, freedBytes, skippedFiles));
                    }
                    catch
                    {
                        // File is in use or locked by another process - safely skip without stopping!
                        skippedFiles++;
                    }
                }

                // Delete subdirectories and their contents
                foreach (var subDir in dirInfo.EnumerateDirectories())
                {
                    if (ct.IsCancellationRequested) break;
                    DeleteDirectoryRecursive(subDir, ref deletedFiles, ref freedBytes, ref skippedFiles, progress, ct);
                }
            }
            catch { }
        }, ct);

        // Recompute remaining
        var (remBytes, remFiles) = ComputeDirectorySize(item.TargetPath, CancellationToken.None);
        item.Size = remBytes;
        item.ItemCount = remFiles;
        item.Status = skippedFiles > 0 ? $"Cleaned ({skippedFiles} locked)" : "Cleaned";

        return (deletedFiles, freedBytes, skippedFiles);
    }

    private void DeleteDirectoryRecursive(
        DirectoryInfo dir, 
        ref int deleted, 
        ref long freed, 
        ref int skipped, 
        IProgress<CleanProgress>? progress, 
        CancellationToken ct)
    {
        if (ct.IsCancellationRequested) return;

        try
        {
            foreach (var file in dir.EnumerateFiles())
            {
                if (ct.IsCancellationRequested) break;
                try
                {
                    long len = file.Length;
                    if ((file.Attributes & FileAttributes.ReadOnly) != 0)
                    {
                        file.Attributes &= ~FileAttributes.ReadOnly;
                    }
                    file.Delete();
                    deleted++;
                    freed += len;
                    progress?.Report(new CleanProgress(file.Name, deleted, freed, skipped));
                }
                catch
                {
                    skipped++;
                }
            }

            foreach (var sub in dir.EnumerateDirectories())
            {
                if (ct.IsCancellationRequested) break;
                DeleteDirectoryRecursive(sub, ref deleted, ref freed, ref skipped, progress, ct);
            }

            // Remove empty folder if unlocked
            try
            {
                dir.Delete(false);
            }
            catch { }
        }
        catch
        {
            skipped++;
        }
    }
