        if (Directory.Exists(steamHttp))
        {
            appCategory.AddItem(new CleanItem
            {
                Name = "Steam Web Cache",
                TargetPath = steamHttp,
                Description = "Embedded Chromium store and community browser cache for Steam.",
                Safety = SafetyLevel.Safe
