using System.Diagnostics;
using System.IO;
using DiskSweep.Core.Models;

namespace DiskSweep.Core.Services;

public class CleanerService
{
    public record CleanProgress(string CurrentItem, int FilesDeleted, long BytesFreed, int FilesSkipped);

    public List<CleanCategory> InitializeCategories()
    {
        if (PlatformInfo.IsMacOS)
        {
            return InitializeMacOSCategories();
        }
        else if (PlatformInfo.IsLinux)
        {
            return InitializeLinuxCategories();
        }
        else
        {
            return InitializeWindowsCategories();
        }
    }

    #region Windows Categories
    private List<CleanCategory> InitializeWindowsCategories()
    {
        var categories = new List<CleanCategory>();

        string localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        string appData = Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData);
        string userProfile = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        string windir = Environment.GetFolderPath(Environment.SpecialFolder.Windows);

        // 1. System Temporary Files
        var sysCategory = new CleanCategory
        {
            Name = "System Temporary Files",
            Description = "Temporary files created by Windows and running applications.",
            Icon = "⚡"
        };

        sysCategory.AddItem(new CleanItem
        {
            Name = "User Temp Files",
            TargetPath = Path.GetTempPath(),
            Description = "Temporary working files created by user applications. Safe to clean.",
            Safety = SafetyLevel.Safe
        });

        string winTemp = Path.Combine(windir, "Temp");
        if (Directory.Exists(winTemp))
        {
            sysCategory.AddItem(new CleanItem
            {
                Name = "Windows System Temp",
                TargetPath = winTemp,
                Description = "System-level temporary files generated by Windows background services.",
                Safety = SafetyLevel.Safe
            });
        }

        string prefetch = Path.Combine(windir, "Prefetch");
        if (Directory.Exists(prefetch))
        {
            sysCategory.AddItem(new CleanItem
            {
                Name = "Windows Prefetch",
                TargetPath = prefetch,
                Description = "Pre-computed application launch trace files. Automatically recreated by Windows.",
                Safety = SafetyLevel.Recommended
            });
        }

        categories.Add(sysCategory);

        // 2. Windows Updates & Diagnostics
        var updateCategory = new CleanCategory
        {
            Name = "Windows Update & Crash Dumps",
            Description = "Downloaded installation updates and crash diagnostic memory dumps.",
            Icon = "🛠️"
        };

        string softwareDist = Path.Combine(windir, "SoftwareDistribution", "Download");
        if (Directory.Exists(softwareDist))
        {
            updateCategory.AddItem(new CleanItem
            {
                Name = "Windows Update Cache",
                TargetPath = softwareDist,
                Description = "Cached installation packages for completed Windows updates. Safe to purge.",
                Safety = SafetyLevel.Safe
            });
        }

        string werUser = Path.Combine(localAppData, "Microsoft", "Windows", "WER");
        if (Directory.Exists(werUser))
        {
            updateCategory.AddItem(new CleanItem
            {
                Name = "Windows Error Reporting (User)",
                TargetPath = werUser,
                Description = "Error and diagnostic crash reports saved by the operating system.",
                Safety = SafetyLevel.Safe
            });
        }

        string crashDumps = Path.Combine(localAppData, "CrashDumps");
        if (Directory.Exists(crashDumps))
        {
            updateCategory.AddItem(new CleanItem
            {
                Name = "User Crash Dumps",
                TargetPath = crashDumps,
                Description = "Process crash dumps (.dmp) created during unexpected application crashes.",
                Safety = SafetyLevel.Safe
            });
        }

        categories.Add(updateCategory);

        // 3. GPU Shader Caches
        var gpuCategory = new CleanCategory
        {
            Name = "Graphics & Shader Caches",
            Description = "Precompiled GPU shader binaries. Safely rebuilds when launching games.",
            Icon = "🎮"
        };

        string d3dCache = Path.Combine(localAppData, "D3DSCache");
        if (Directory.Exists(d3dCache))
        {
            gpuCategory.AddItem(new CleanItem
            {
                Name = "DirectX Shader Cache",
                TargetPath = d3dCache,
                Description = "DirectX 11/12 compiled shader pipeline state caches.",
                Safety = SafetyLevel.Safe
            });
        }

        string nvCache = Path.Combine(localAppData, "NVIDIA", "DXCache");
        if (Directory.Exists(nvCache))
        {
            gpuCategory.AddItem(new CleanItem
            {
                Name = "NVIDIA DXCache",
                TargetPath = nvCache,
                Description = "NVIDIA compiled DirectX shader cache files.",
                Safety = SafetyLevel.Safe
            });
        }

        string amdCache = Path.Combine(localAppData, "AMD", "DxCache");
        if (Directory.Exists(amdCache))
        {
            gpuCategory.AddItem(new CleanItem
            {
                Name = "AMD Radeon Shader Cache",
                TargetPath = amdCache,
                Description = "AMD Radeon Adrenalin compiled shader pipeline cache.",
                Safety = SafetyLevel.Safe
            });
        }

        if (gpuCategory.Items.Count > 0) categories.Add(gpuCategory);

        // 4. Web Browser Caches
        var browserCategory = new CleanCategory
        {
            Name = "Web Browser Caches",
            Description = "Temporary website images, scripts, and media. Logins and cookies are preserved.",
            Icon = "🌐"
        };

        AddBrowserTarget(browserCategory, "Google Chrome", Path.Combine(localAppData, "Google", "Chrome", "User Data", "Default", "Cache"));
        AddBrowserTarget(browserCategory, "Microsoft Edge", Path.Combine(localAppData, "Microsoft", "Edge", "User Data", "Default", "Cache"));
        AddBrowserTarget(browserCategory, "Brave Browser", Path.Combine(localAppData, "BraveSoftware", "Brave-Browser", "User Data", "Default", "Cache"));
        AddBrowserTarget(browserCategory, "Mozilla Firefox", Path.Combine(localAppData, "Mozilla", "Firefox", "Profiles"));
        AddBrowserTarget(browserCategory, "Opera GX", Path.Combine(localAppData, "Opera Software", "Opera GX Stable", "Cache"));

        if (browserCategory.Items.Count > 0) categories.Add(browserCategory);

        // 5. Application & Gaming Caches
        var appCategory = new CleanCategory
        {
            Name = "Application & Gaming Caches",
            Description = "Cached streams, images, and voice data from everyday software.",
            Icon = "📦"
        };

        string discordCache = Path.Combine(appData, "discord", "Cache");
        if (Directory.Exists(discordCache))
        {
            appCategory.AddItem(new CleanItem
            {
                Name = "Discord Media Cache",
