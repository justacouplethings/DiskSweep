    private void AddTargetIfPathExists(CleanCategory category, string name, string path, SafetyLevel safety)
    {
        if (Directory.Exists(path))
        {
            category.AddItem(new CleanItem
            {
                Name = name,
                TargetPath = path,
                Description = $"Clean temporary files in {path}.",
                Safety = safety
            });
        }
    }

    private void AddBrowserTarget(CleanCategory cat, string name, string path)
