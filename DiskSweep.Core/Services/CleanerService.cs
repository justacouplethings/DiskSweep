        AddDevTarget(devCategory, "Node.js NPM Cache", Path.Combine(appData, "npm-cache"));
        AddDevTarget(devCategory, "Rust Cargo Registry", Path.Combine(userProfile, ".cargo", "registry", "cache"));

        if (devCategory.Items.Count > 0) categories.Add(devCategory);

        // 7. Recycle Bin
        var binCategory = new CleanCategory
        {
            Name = "Windows Recycle Bin",
            Description = "Deleted items currently held in the Windows Recycle Bin.",
            Icon = "🗑️"
        };

        binCategory.AddItem(new CleanItem
