        if (Directory.Exists(spotifyCache))
        {
            appCategory.AddItem(new CleanItem
            {
                Name = "Spotify Stream Cache",
                TargetPath = spotifyCache,
                Description = "Locally cached music streams and album art previews.",
                Safety = SafetyLevel.Safe
