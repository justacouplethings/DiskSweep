    #region macOS Categories
    private List<CleanCategory> InitializeMacOSCategories()
    {
        var categories = new List<CleanCategory>();
        string home = PlatformInfo.UserHomePath;
        string userCaches = Path.Combine(home, "Library", "Caches");
        string userLogs = Path.Combine(home, "Library", "Logs");

        // 1. macOS User & App Caches
        var cacheCat = new CleanCategory
        {
            Name = "User Application Caches",
            Description = "Temporary app cache files, HTTP web caches, and media previews.",
            Icon = "⚡"
        };

        AddTargetIfPathExists(cacheCat, "Google Chrome Cache", Path.Combine(userCaches, "Google", "Chrome", "Default", "Cache"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Safari Web Cache", Path.Combine(userCaches, "com.apple.Safari"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Mozilla Firefox Cache", Path.Combine(userCaches, "Firefox", "Profiles"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Microsoft Edge Cache", Path.Combine(userCaches, "Microsoft Edge", "Default", "Cache"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Discord Cache", Path.Combine(userCaches, "com.hnc.Discord"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Spotify Cache", Path.Combine(userCaches, "com.spotify.client"), SafetyLevel.Safe);
        AddTargetIfPathExists(cacheCat, "Homebrew Downloads Cache", Path.Combine(userCaches, "Homebrew"), SafetyLevel.Safe);

        // Fallback root cache if none of the above are matched specifically
        if (cacheCat.Items.Count == 0 && Directory.Exists(userCaches))
        {
            AddTargetIfPathExists(cacheCat, "macOS User Caches", userCaches, SafetyLevel.Recommended);
        }
        categories.Add(cacheCat);

        // 2. Logs & Diagnostic Crash Reports
        var logCat = new CleanCategory
        {
            Name = "Logs & Diagnostic Reports",
            Description = "System log files, application crash dumps, and diagnostic telemetry.",
            Icon = "🛠️"
        };

        AddTargetIfPathExists(logCat, "Diagnostic Crash Reports", Path.Combine(userLogs, "DiagnosticReports"), SafetyLevel.Safe);
        AddTargetIfPathExists(logCat, "User App Logs", userLogs, SafetyLevel.Safe);
        AddTargetIfPathExists(logCat, "System Logs (/var/log)", "/var/log", SafetyLevel.Recommended);
        if (logCat.Items.Count > 0) categories.Add(logCat);

        // 3. Developer Caches (Xcode, Pip, Cargo, NPM)
        var devCat = new CleanCategory
        {
            Name = "Developer Build Caches",
            Description = "Xcode build artifacts, simulator caches, and package manager downloads.",
            Icon = "💻"
        };

        string xcodeDerived = Path.Combine(home, "Library", "Developer", "Xcode", "DerivedData");
        AddTargetIfPathExists(devCat, "Xcode DerivedData", xcodeDerived, SafetyLevel.Safe);
        AddTargetIfPathExists(devCat, "Xcode iOS DeviceSupport", Path.Combine(home, "Library", "Developer", "Xcode", "iOS DeviceSupport"), SafetyLevel.Recommended);
        AddTargetIfPathExists(devCat, "Python Pip Cache", Path.Combine(userCaches, "pip"), SafetyLevel.Safe);
        AddTargetIfPathExists(devCat, "Node.js NPM Cache", Path.Combine(home, ".npm", "_cacache"), SafetyLevel.Safe);
        AddTargetIfPathExists(devCat, "Rust Cargo Registry", Path.Combine(home, ".cargo", "registry", "cache"), SafetyLevel.Safe);
        if (devCat.Items.Count > 0) categories.Add(devCat);

        // 4. Temporary & Trash
        var trashCat = new CleanCategory
        {
            Name = "macOS Trash & Temporary Files",
            Description = "User Trash folder and system temporary directory.",
            Icon = "🗑️"
        };

        string trashPath = Path.Combine(home, ".Trash");
        trashCat.AddItem(new CleanItem
        {
            Name = "macOS Trash",
            TargetPath = trashPath,
            Description = "Purge all files currently residing in ~/.Trash.",
            Safety = SafetyLevel.Recommended,
            IsRecycleBin = true,
            CustomCleanAction = (item, ct) => Task.FromResult(TrashService.EmptyTrash())
        });

        AddTargetIfPathExists(trashCat, "System Temp (/tmp)", "/tmp", SafetyLevel.Safe);
        categories.Add(trashCat);

        return categories;
    }
