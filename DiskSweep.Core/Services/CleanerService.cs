    public async Task ScanItemAsync(CleanItem item, CancellationToken ct)
    {
        await Task.Run(() =>
        {
            if (item.IsRecycleBin)
            {
                var (size, count) = TrashService.GetTrashStats();
                item.Size = size;
                item.ItemCount = (int)Math.Min(count, int.MaxValue);
                item.Status = size > 0 ? $"{item.SizeFormatted} ({item.ItemCount:N0} items)" : "Empty";
                return;
            }

            if (!Directory.Exists(item.TargetPath))
            {
                item.Size = 0;
                item.ItemCount = 0;
                item.Status = "Not Found / Clean";
                return;
            }

            long totalBytes = 0;
            int totalFiles = 0;

            try
            {
                var dirInfo = new DirectoryInfo(item.TargetPath);
                var files = dirInfo.EnumerateFiles("*", SearchOption.AllDirectories);

                foreach (var file in files)
                {
                    if (ct.IsCancellationRequested) break;
                    try
                    {
                        totalBytes += file.Length;
                        totalFiles++;
                    }
                    catch { }
                }
            }
            catch
            {
                item.Status = "Access Denied";
                return;
            }

            item.Size = totalBytes;
            item.ItemCount = totalFiles;
            item.Status = totalFiles > 0 ? $"{item.SizeFormatted} ({totalFiles:N0} files)" : "Clean";
        }, ct);
    }

    public async Task<(int DeletedFiles, long FreedBytes, int SkippedFiles)> CleanItemAsync(
        CleanItem item,
        bool safeMode24Hours,
        bool moveToRecycleBin,
        IProgress<CleanProgress>? progress,
        CancellationToken ct)
    {
        return await Task.Run(async () =>
        {
            if (item.IsRecycleBin)
            {
                long freed = item.Size;
                int count = item.ItemCount;
                if (item.CustomCleanAction != null)
                {
                    await item.CustomCleanAction(item, ct);
                }
                else
                {
                    TrashService.EmptyTrash();
                }

                item.Size = 0;
                item.ItemCount = 0;
                item.Status = "Emptied";
                progress?.Report(new CleanProgress("Trash Purged", count, freed, 0));
                return (count, freed, 0);
            }

            if (!Directory.Exists(item.TargetPath)) return (0, 0, 0);

            int deletedCount = 0;
            long freedBytes = 0;
            int skippedCount = 0;

            DateTime threshold = DateTime.Now.AddHours(-24);
            var dirInfo = new DirectoryInfo(item.TargetPath);

            FileInfo[] files;
            try
            {
                files = dirInfo.GetFiles("*", SearchOption.AllDirectories);
            }
            catch
            {
                return (0, 0, 0);
            }

            foreach (var file in files)
            {
                if (ct.IsCancellationRequested) break;

                // 24-hour safety cushion
                if (safeMode24Hours && file.LastWriteTime > threshold)
                {
                    skippedCount++;
                    continue;
                }

                try
                {
                    long length = file.Length;
                    string filePath = file.FullName;

                    bool deleted = false;
                    if (moveToRecycleBin)
                    {
                        deleted = TrashService.MoveToTrash(filePath);
                    }

                    if (!deleted)
                    {
                        file.Delete();
                        deleted = true;
                    }

                    if (deleted)
                    {
                        deletedCount++;
                        freedBytes += length;
                        progress?.Report(new CleanProgress(file.Name, deletedCount, freedBytes, skippedCount));
                    }
                }
                catch
                {
                    skippedCount++;
                }
            }

            // Remove empty subdirectories
            try
            {
                foreach (var dir in dirInfo.GetDirectories("*", SearchOption.AllDirectories).OrderByDescending(d => d.FullName.Length))
                {
                    if (ct.IsCancellationRequested) break;
                    try
                    {
                        if (!dir.EnumerateFileSystemInfos().Any())
                        {
                            dir.Delete();
                        }
                    }
                    catch { }
                }
            }
            catch { }

            item.Size = Math.Max(0, item.Size - freedBytes);
            item.ItemCount = Math.Max(0, item.ItemCount - deletedCount);
            item.Status = item.ItemCount > 0 ? $"{item.SizeFormatted} left" : "Cleaned";

            return (deletedCount, freedBytes, skippedCount);
        }, ct);
    }
